package introducao_ao_java;

public class _09VariaveisGlobalLocal {

	// Variável global
	static int variavelGlobal = 25;
	
	public static void main(String[] args) {
		
		// Variável local
		int variavelLocal = 36;
		
		System.out.println("Valor da variável global = " + variavelGlobal);
		System.out.println("Valor da variável local = " + variavelLocal);

	}

}
